import fs from 'node:fs';
import zlib from 'node:zlib';
import crypto from 'node:crypto';
import { execFileSync } from 'node:child_process';
const data = Array.from({length:5},(_,i)=>fs.readFileSync('bundle.part'+(i+1)+'.txt','utf8').trim()).join('');
const bytes=Buffer.from(data,'base64');
const digest=crypto.createHash('sha256').update(bytes).digest('hex');
if(digest!=='4cb5481d30bfc628cf7f9b233f5a9e8a8d5b4eb1edacbab373e8b3cd07eabf35') throw Error('Source archive checksum mismatch: '+digest);
const tar=zlib.brotliDecompressSync(bytes);
fs.writeFileSync('_source.tar',tar);
execFileSync('tar',['-xf','_source.tar'],{stdio:'inherit'});
fs.rmSync('_source.tar');
console.log('FRACTURE source unpacked.');
